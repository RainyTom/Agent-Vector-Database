#!/usr/bin/env python3
"""Export L2 vector inputs for five synthetic-hierarchy CCS evaluations.

The three SIFT inputs are nested prefixes of ONE HDF5 corpus, not three
independent datasets. HDF5 has no hierarchy labels; prep_ccs.py synthesizes
all labels and query scopes separately.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import h5py
import numpy as np

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUT = ROOT / "production" / "nested-attr-vector-search" / "work" / "five_l2" / "inputs"
SOURCES = {
    "sift25k": ("sift-128-euclidean.hdf5", 25_000, 128),
    "sift50k": ("sift-128-euclidean.hdf5", 50_000, 128),
    "sift100k": ("sift-128-euclidean.hdf5", 100_000, 128),
    "mnist25k": ("mnist-784-euclidean.hdf5", 25_000, 784),
    "fashion-mnist25k": ("fashion-mnist-784-euclidean.hdf5", 25_000, 784),
}
CHUNK = 4096


def export_array(dataset: h5py.Dataset, rows: int, dest: Path) -> None:
    """Check original HDF5 values before converting to exact u8-valued float32."""
    with dest.open("wb") as out:
        for start in range(0, rows, CHUNK):
            block = dataset[start:min(start + CHUNK, rows)]
            if (not np.issubdtype(block.dtype, np.number)
                    or not np.isfinite(block).all()
                    or np.any((block < 0) | (block > 255))
                    or np.any(block != np.floor(block))):
                raise ValueError(f"{dataset.name}[{start}:{min(start + CHUNK, rows)}] "
                                 "must contain finite integers in [0,255]")
            out.write(np.asarray(block, dtype=np.float32, order="C").tobytes())


def export_one(name: str, out_root: Path) -> None:
    filename, n, dim = SOURCES[name]
    source = ROOT / "datasets" / filename
    with h5py.File(source, "r") as h5:
        train, test = h5["train"], h5["test"]
        if (len(train.shape) != 2 or len(test.shape) != 2
                or train.shape[1] != dim or test.shape[1] != dim
                or train.shape[0] < n or test.shape[0] != 10_000):
            raise ValueError(f"{source}: expected train >= {n} x {dim} and test 10000 x {dim}; "
                             f"got train {train.shape}, test {test.shape}")

        out = out_root / name
        out.mkdir(parents=True, exist_ok=True)
        export_array(train, n, out / "base.f32")
        export_array(test, test.shape[0], out / "test.f32")
        provenance = {
            "name": name,
            "source_file": str(source.relative_to(ROOT)),
            "source_n": int(train.shape[0]),
            "selected_n": n,
            "selection": f"first {n} train vectors",
            "test_n": int(test.shape[0]),
            "test_selection": "all test vectors",
            "d": dim,
            "output_dtype": "float32",
            "value_validation": "source train prefix and full test: finite integer values in [0,255]",
            "metric": "squared_l2",
            "sift_subsets_overlap": name.startswith("sift"),
            "hierarchy": "not present in source; labels/scopes generated by prep_ccs.py",
        }
        if name.startswith("sift"):
            provenance["shared_corpus"] = "sift-128-euclidean.hdf5; 25k/50k/100k are nested prefixes"
        (out / "meta.json").write_text(json.dumps(provenance, indent=2) + "\n")
        print(json.dumps(provenance))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-root", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--only", choices=tuple(SOURCES))
    args = ap.parse_args()
    for name in (args.only,) if args.only else SOURCES:
        export_one(name, args.out_root)


if __name__ == "__main__":
    main()
